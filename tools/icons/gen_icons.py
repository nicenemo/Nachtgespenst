#!/usr/bin/env python3
"""Subset Material Icons (Apache License 2.0, (c) Google) to the glyphs listed in ICONS and emit
   include/IconCodes.h (UTF-8 string macros IC_<NAME>) + src/icon_font_data.c (TTF bytes).
   Needs: pip install fonttools.  Run from repo root: python3 tools/icons/gen_icons.py"""
import subprocess, sys, os
ICONS = """content_copy content_paste content_cut undo redo search select_all save print refresh description
table_chart slideshow mail groups sticky_note_2 public folder lock keyboard_return keyboard_tab backspace
space_bar arrow_upward arrow_downward arrow_back arrow_forward first_page last_page keyboard_double_arrow_up
keyboard_double_arrow_down menu screenshot_monitor keyboard_capslock pause play_arrow power_settings_new
bedtime wb_sunny skip_previous skip_next volume_off volume_down volume_up stop language calendar_month
calculate memory brightness_low brightness_high mic_off videocam call_end reply_all fullscreen close
radio_button_checked subdirectory_arrow_right north restart_alt restore_page play_circle dialpad""".split()
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.abspath(os.path.join(here, "..", ".."))
cp = dict(l.split() for l in open(os.path.join(here, "MaterialIcons-Regular.codepoints")))
uni = [cp[n] for n in ICONS]
out = os.path.join(here, "subset.ttf")
subprocess.check_call([sys.executable, "-m", "fontTools.subset", os.path.join(here, "MaterialIcons-Regular.ttf"),
    "--unicodes=" + ",".join("U+" + u for u in uni), "--output-file=" + out, "--no-hinting", "--drop-tables+=GSUB,GPOS,GDEF,kern,name,OS/2,post",
    "--layout-features=", "--glyph-names"])
data = open(out, "rb").read()
with open(os.path.join(root, "include", "IconCodes.h"), "w") as f:
    f.write("#pragma once\n// GENERATED by tools/icons/gen_icons.py -- Material Icons (Apache-2.0, Google). Do not edit.\n")
    for n, u in zip(ICONS, uni):
        c = int(u, 16); b = chr(c).encode("utf-8")
        f.write('#define IC_%s "%s"\n' % (n.upper(), "".join("\\x%02X" % x for x in b)))
with open(os.path.join(root, "src", "icon_font_data.c"), "w") as f:
    f.write("// GENERATED by tools/icons/gen_icons.py. Subset of Material Icons, (c) Google, Apache License 2.0.\n")
    f.write("// https://github.com/google/material-design-icons  -- https://www.apache.org/licenses/LICENSE-2.0\n")
    f.write("#include <stdint.h>\n#include <stddef.h>\nconst uint8_t ng_icon_ttf[] = {\n")
    for i in range(0, len(data), 16):
        f.write(",".join("0x%02X" % x for x in data[i:i+16]) + ",\n")
    f.write("};\nconst size_t ng_icon_ttf_len = sizeof(ng_icon_ttf);\n")
print(len(ICONS), "icons,", len(data), "bytes")
