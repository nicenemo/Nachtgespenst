#!/usr/bin/env python3
"""Writes src/geist_font_data.c from the Geist TTF files (SIL OFL 1.1, see tools/fonts/OFL.txt).
Run from the repository root: python3 tools/fonts/gen_fonts.py"""
import pathlib
root = pathlib.Path(__file__).resolve().parents[2]
out = ["// GENERATED by tools/fonts/gen_fonts.py. Geist Sans Bold and Geist Mono, (c) Vercel, SIL Open Font Licence 1.1 (tools/fonts/OFL.txt).",
       "#include <stdint.h>", "#include <stddef.h>"]
for sym, name in (("ng_geist_bold", "Geist-Bold.ttf"), ("ng_geist_mono", "GeistMono-Regular.ttf")):
    data = (root / "tools/fonts" / name).read_bytes()
    out.append(f"const uint8_t {sym}_ttf[] = {{")
    for i in range(0, len(data), 24):
        out.append(",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"const size_t {sym}_ttf_len = {len(data)};")
(root / "src/geist_font_data.c").write_text("\n".join(out) + "\n")
print("wrote src/geist_font_data.c")
